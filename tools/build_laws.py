"""Build data/laws.js: the central-Acts catalogue plus the key-Act explainers.

Usage:
  python -I tools/build_laws.py <work-dir> data/laws.js

<work-dir> must contain:
  all*.json   India Code search pages (DSpace 7 API), fetched with e.g.
              curl "https://indiacode.gov.in/server/api/discover/search/objects?scope=69a0c1fb-7b22-4481-b16a-1dc59b5d02e6&dsoType=ITEM&size=100&page=N"
  out*.jsonl  subject + constitutional basis per Act, keyed by uuid  {u,s,l,e,a,how,n}
  key*.json   key-Act explainers (arrays of objects; schema in data/laws.js)
  groups.json [[group title, [key ids...]], ...]
"""
import glob
import html
import json
import os
import re
import sys
from datetime import date

work, out = sys.argv[1], sys.argv[2]

SUBJECTS = [
    ("criminal", "Crime, police & courts"), ("rights", "Rights & social justice"), ("family", "Family & personal law"),
    ("elections", "Elections & Parliament"), ("government", "Government & administration"), ("states", "States, UTs & local government"),
    ("finance", "Tax & public finance"), ("banking", "Banking, money & insurance"), ("business", "Business, trade & consumers"),
    ("labour", "Labour & employment"), ("land", "Land, property & housing"), ("environment", "Environment, forests & wildlife"),
    ("health", "Health & medicine"), ("education", "Education, culture & science"), ("infrastructure", "Transport, energy & communications"),
    ("agriculture", "Agriculture & food"), ("defence", "Defence & security"), ("international", "Foreign affairs & treaties"),
]
SUBJ = {k for k, _ in SUBJECTS}


def clean(s):
    s = html.unescape(s or "").replace("�", "’")
    s = re.sub(r"<[^>]+>", " ", s)
    return re.sub(r"\s+", " ", s).strip()


acts = {}
for f in sorted(glob.glob(os.path.join(work, "all*.json"))):
    d = json.load(open(f, encoding="utf-8"))
    for o in d["_embedded"]["searchResult"]["_embedded"]["objects"]:
        x = o["_embedded"]["indexableObject"]
        m = x["metadata"]
        g = lambda k: (m.get(k) or [{"value": ""}])[0]["value"]
        if g("dc.identifier.repealed") == "true":
            continue
        acts[x["uuid"]] = dict(u=x["uuid"], t=clean(x["name"]), y=g("dc.date.act_year"), n=g("dc.identifier.act_number"),
                               ministry=clean(g("dc.identifier.ministry_name")).replace("Jal Shaktri", "Jal Shakti"),
                               lt=clean(g("dc.title.long_title")))

basis = {}
for f in sorted(glob.glob(os.path.join(work, "out*.jsonl"))):
    for line in open(f, encoding="utf-8"):
        if line.strip():
            r = json.loads(line)
            basis[r["u"]] = r

key = []
for f in sorted(glob.glob(os.path.join(work, "key*.json"))):
    key += json.load(open(f, encoding="utf-8"))
groups = json.load(open(os.path.join(work, "groups.json"), encoding="utf-8"))
order = {i: n for n, i in enumerate(i for _, ids in groups for i in ids)}
key.sort(key=lambda k: order.get(k["id"], 9999))

ministries = sorted({a["ministry"] for a in acts.values() if a["ministry"]})
midx = {m: i for i, m in enumerate(ministries)}
keyByU = {k["u"]: k["id"] for k in key if k.get("u")}

rows, missing = [], []
for a in sorted(acts.values(), key=lambda a: (int(a["y"] or 0), int(a["n"]) if a["n"].isdigit() else 9999)):
    b = basis.get(a["u"])
    if not b:
        missing.append(a["t"])
        b = {}
    s = b.get("s") if b.get("s") in SUBJ else "government"
    lt = a["lt"]
    if len(lt) > 240:
        lt = lt[:237].rsplit(" ", 1)[0] + "…"
    r = dict(u=a["u"], t=a["t"], y=a["y"], n=a["n"], m=midx.get(a["ministry"], -1), s=s)
    if lt: r["lt"] = lt
    if b.get("l") in ("I", "II", "III"): r["l"] = b["l"]
    if b.get("e"): r["e"] = [str(e) for e in b["e"]]
    if b.get("a"): r["a"] = [str(e) for e in b["a"]]
    # "stated" only when the long title itself shows the declaration; anything else is our inference
    r["how"] = "stated" if b.get("how") == "stated" and re.search(r"expedient in the public interest|article \d|declared|give effect|convention|treaty|resolutions? (?:have been )?passed", a["lt"], re.I) else "inferred"
    if b.get("n"): r["nt"] = b["n"]
    if a["u"] in keyByU: r["k"] = keyByU[a["u"]]
    rows.append(r)

for k in key:
    k.setdefault("checked", "November 2026")
    for s in k.get("sources", []):  # India Code moved from indiacode.nic.in in 2026
        s["u"] = re.sub(r"^https?://(www\.)?indiacode\.nic\.in", "https://indiacode.gov.in", s["u"])

data = dict(source="India Code (indiacode.gov.in), Legislative Department, Government of India", updated=str(date.today()),
            checked="November 2026", subjects=SUBJECTS, ministries=ministries, groups=groups, key=key, acts=rows)
with open(out, "w", encoding="utf-8", newline="\n") as fh:
    fh.write("/* Central Acts catalogue (from India Code) and key-Act explainers. Generated by tools/build_laws.py. */\n")
    fh.write("window.COI_LAWS = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n")
print(f"{len(rows)} acts, {len(key)} key, {len(missing)} without basis", missing[:5], f"{os.path.getsize(out)//1024} KB")
